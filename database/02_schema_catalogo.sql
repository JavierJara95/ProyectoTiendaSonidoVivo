CREATE DATABASE IF NOT EXISTS sonido_vivo_catalogo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sonido_vivo_catalogo;

CREATE TABLE IF NOT EXISTS categorias (id BIGINT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL UNIQUE, descripcion VARCHAR(500));
CREATE TABLE IF NOT EXISTS marcas (id BIGINT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS productos (id BIGINT AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(20) NOT NULL UNIQUE, nombre VARCHAR(180) NOT NULL, modelo VARCHAR(100) NOT NULL, descripcion VARCHAR(1000), precio DECIMAL(14,2) NOT NULL, stock INT NOT NULL, categoria_id BIGINT NOT NULL, marca_id BIGINT NOT NULL, CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id), CONSTRAINT fk_producto_marca FOREIGN KEY (marca_id) REFERENCES marcas(id), CONSTRAINT chk_producto_precio CHECK (precio >= 0), CONSTRAINT chk_producto_stock CHECK (stock >= 0));

