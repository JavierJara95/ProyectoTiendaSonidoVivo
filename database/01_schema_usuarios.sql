CREATE DATABASE IF NOT EXISTS sonidovivo_usuarios CHARACTER SET utf8mb4;
USE sonidovivo_usuarios;

CREATE TABLE IF NOT EXISTS roles (
  nombre VARCHAR(20) PRIMARY KEY
);
INSERT IGNORE INTO roles (nombre) VALUES ('ROLE_ADMIN'), ('ROLE_VENDEDOR'), ('ROLE_CLIENTE');

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  rol VARCHAR(20) NOT NULL,
  activo BOOLEAN NOT NULL,
  version BIGINT NOT NULL,
  FOREIGN KEY (rol) REFERENCES roles(nombre)
);
